--!strict

local Int = require("./integer")
local Memory = require("./memory")
local CPU = require("./cpu")

local function expect(actual: Int.Int64, hex: string)
    local expected = Int.fromHex(hex)
    assert(Int.eq(actual, expected), string.format("Expected %s, got %08x%08x", hex, actual.hi, actual.lo))
end

local zero = Int.ZERO
local one = Int.ONE
local max = Int.MAX_U64
local minSigned = Int.fromHex("8000000000000000")
local maxSigned = Int.fromHex("7fffffffffffffff")
local a = Int.fromHex("12345678abcdef01")
local b = Int.fromHex("fedcba9876543210")

expect(Int.from(-1), "ffffffffffffffff")
expect(Int.from(-0x100000001), "fffffffeffffffff")
assert(Int.toNumber(Int.from(-1)) == -1)
assert(Int.toNumber(Int.from(-0x100000001)) == -0x100000001)
expect(Int.add(max, one), "0000000000000000")
expect(Int.add(maxSigned, one), "8000000000000000")
expect(Int.sub(zero, one), "ffffffffffffffff")
expect(Int.neg(minSigned), "8000000000000000")
expect(Int.mul(max, max), "0000000000000001")
expect(Int.umulh(max, max), "fffffffffffffffe")
expect(Int.mul(a, b), "5fbae76dd7e12210")
expect(Int.umulh(a, b), "121fa00ae87b192d")
expect(Int.smulh(a, b), "ffeb49923cad2a2c")
expect(Int.smulh(minSigned, minSigned), "4000000000000000")
expect(Int.smulh(max, max), "0000000000000000")
expect(Int.smulh(minSigned, one), "ffffffffffffffff")
expect(Int.udiv(b, a), "000000000000000d")
expect(Int.urem(b, a), "12345677bcdf0f03")
expect(Int.udiv(max, Int.fromHex("8000000000000001")), "0000000000000001")
expect(Int.urem(max, Int.fromHex("8000000000000001")), "7ffffffffffffffe")
expect(Int.udiv(max, Int.fromHex("100000001")), "00000000ffffffff")
expect(Int.urem(max, Int.fromHex("100000001")), "0000000000000000")
expect(Int.sdiv(Int.from(-7), Int.from(2)), "fffffffffffffffd")
expect(Int.srem(Int.from(-7), Int.from(2)), "ffffffffffffffff")
expect(Int.sdiv(minSigned, max), "8000000000000000")
assert(not pcall(Int.udiv, one, zero))

expect(Int.shl(a, 32), "abcdef0100000000")
expect(Int.shr(a, 32), "0000000012345678")
expect(Int.shl(one, 63), "8000000000000000")
expect(Int.shr(minSigned, 63), "0000000000000001")
expect(Int.sar(minSigned, 63), "ffffffffffffffff")
expect(Int.sar(minSigned, 32), "ffffffff80000000")
expect(Int.sar(minSigned, 31), "ffffffff00000000")
expect(Int.sar(minSigned, 64), "ffffffffffffffff")
expect(Int.shl(one, 64), "0000000000000000")
expect(Int.shr(max, 64), "0000000000000000")
expect(Int.shl(a, -32), "0000000012345678")
expect(Int.sar(one, -63), "8000000000000000")
expect(Int.signExtend(Int.from(0x80), 8), "ffffffffffffff80")
expect(Int.signExtend(Int.from(0x80000000), 32), "ffffffff80000000")
expect(Int.zeroExtend(max, 33), "00000001ffffffff")
expect(Int.zeroExtend(max, 0), "0000000000000000")
expect(Int.extractBits(a, 28, 35), "000000000000008a")
assert(Int.clz64(zero) == 64 and Int.clz64(one) == 63 and Int.clz64(minSigned) == 0)
expect(Int.rbit64(Int.fromHex("0123456789abcdef")), "f7b3d591e6a2c480")
expect(Int.rev64(Int.fromHex("0123456789abcdef")), "efcdab8967452301")
expect(Int.rev32(a), "0000000001efcdab")
expect(Int.rev16(a), "00000000cdab01ef")
assert(Int.lt(minSigned, zero) and Int.gt(maxSigned, max))
assert(Int.ugt(minSigned, maxSigned) and Int.ult(one, max))
assert(Int.eq(Int.from(42), Int.from(42)))

local mem = Memory.new()
for _, offset in { 8, 4092, 4093, 4095 } do
    local addr = Int.from(offset)
    mem:writeU64(addr, a)
    expect(mem:readU64(addr), "12345678abcdef01")
    assert(mem:readU8(addr) == 1)
    assert(mem:readU32(addr) == 0xabcdef01)
    assert(mem:readU32(Int.add(addr, Int.from(4))) == 0x12345678)
end

local cpu = CPU.new(mem)
expect(cpu:addWithCarry64(max, zero, true), "0000000000000000")
assert(cpu.C and cpu.Z and not cpu.V)
expect(cpu:addWithCarry64(maxSigned, one, false), "8000000000000000")
assert(cpu.N and cpu.V and not cpu.C)
expect(cpu:addWithCarry32(Int.MASK32, zero, true), "0000000000000000")
assert(cpu.C and cpu.Z and not cpu.V)
cpu:writeX(0, a)
cpu:writeW(0, b)
expect(cpu:readX(0), "0000000076543210")
cpu:writeX(31, a)
expect(cpu:readX(31), "0000000000000000")
expect(Int.ZERO, "0000000000000000")

print("Paired-word arithmetic, CPU flags, and cross-page memory checks passed")
